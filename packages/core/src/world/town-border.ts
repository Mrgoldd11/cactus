/**
 * Граница города: круг вокруг центра, радиус — `Town::getRadius()` игры.
 *
 * Разобрано из exe (Steam 1.0.65, `Town::getRadius` = RVA 0x925FE0) и сверено с игрой через мост:
 * Хаб (тип 2) — 2500, База Мятежников (тип 9) — 437.5. Радиус зависит только от типа города
 * (`type` записи TOWN, число как у `townType` игры) и множителя `town radius mult`:
 *   тип 2 (город) — 2500; 3 (деревня) — 937.5; 4 (руины) — 875; 9 — 437.5;
 *   8 и 10 — 0 (нет границы); остальное (0 гнездо, 1 застава, 5–7 лагерь/армия/тюрьма, неизвестное) — 1250.
 * Не учтено: у игры есть редкая ветка (поле объекта города 0x51C > 1 — в данных мода его нет),
 * тогда радиус берётся из этого поля.
 */

/** Тип по умолчанию у записи TOWN без поля `type` — TOWN_OUTPOST. */
export const TOWN_DEFAULT_TYPE = 1;

const BASE_RADIUS: Record<number, number> = { 2: 2500, 3: 937.5, 4: 875, 8: 0, 9: 437.5, 10: 0 };

/** Радиус границы города по типу и множителю `town radius mult`; 0 — границы нет. */
export function townBorderRadius(type: number = TOWN_DEFAULT_TYPE, mult = 1): number {
  const base = BASE_RADIUS[type] ?? 1250;
  return base * mult;
}
